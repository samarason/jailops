package dtest

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"testing"
	"time"

	"jailops.net/jailops/internal/priv"
	"jailops.net/jailops/internal/sys/run"
)

// Files of the simulated host's etc directory before any change.
const (
	HostResolv = "# Generated by resolvconf\nsearch corp.example.org\nnameserver 198.51.100.1\n"
	HostNTP    = "# /etc/ntp.conf\npool 0.freebsd.pool.ntp.org iburst\n"
	HostRC     = "hostname=\"old.example.org\"\nsshd_enable=\"YES\"\n"
	HostPF     = "# the administrator's own rules\nanchor \"jailops/*\"\npass all\n"
)

// HostSim is the host that host management changes in tests: an etc directory and stand-ins for hostname(1),
// sysrc(8), service(8) and ntpq(8) that act on it, behind a real helper (priv.Local) so every request passes the
// helper's own rules, the admin assertion included.
type HostSim struct {
	Etc   string
	Local *priv.Local
	Run   *run.Fake

	mu       sync.Mutex
	hostname string
	restarts int
	ntpq     string
	pfOn     bool
	pfLoaded string
	timer    func()
}

var reSysrc = regexp.MustCompile(`^([a-z_]+)=(.*)$`)

func newHostSim(t testing.TB, dir string, modules []string) *HostSim {
	h := &HostSim{Etc: filepath.Join(dir, "etc"), Run: run.NewFake(), hostname: "old.example.org",
		ntpq: "*192.0.2.123     .GPS.            1 u   12   64  377    1.234    0.012   0.010\n"}
	h.pfOn, h.pfLoaded = true, HostPF
	for n, s := range map[string]string{"resolv.conf": HostResolv, "ntp.conf": HostNTP, "rc.conf": HostRC, "pf.conf": HostPF} {
		if err := os.MkdirAll(h.Etc, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(h.Etc, n), []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	h.Run.Add(run.Rule{Name: "/bin/hostname", Args: []string{run.RestArgs}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		if len(c.Args) == 1 {
			h.hostname = c.Args[0]
			return run.Result{}, nil
		}
		return run.Result{Stdout: []byte(h.hostname + "\n")}, nil
	}})
	h.Run.Add(run.Rule{Name: "/usr/sbin/sysrc", Args: []string{"-f", run.AnyArg, run.AnyArg}, Fn: func(c run.Cmd) (run.Result, error) {
		m := reSysrc.FindStringSubmatch(c.Args[2])
		b, err := os.ReadFile(c.Args[1])
		if m == nil || err != nil {
			return run.Result{ExitCode: 1}, &run.ExitError{Name: c.Name, Code: 1}
		}
		lines := strings.Split(strings.TrimSuffix(string(b), "\n"), "\n")
		line, done := m[1]+`="`+m[2]+`"`, false
		for i, l := range lines {
			if strings.HasPrefix(l, m[1]+"=") {
				lines[i], done = line, true
			}
		}
		if !done {
			lines = append(lines, line)
		}
		return run.Result{}, os.WriteFile(c.Args[1], []byte(strings.Join(lines, "\n")+"\n"), 0o644)
	}})
	h.Run.Add(run.Rule{Name: "/usr/sbin/sysrc", Args: []string{"-f", run.AnyArg, "-x", run.AnyArg}, Fn: func(c run.Cmd) (run.Result, error) {
		b, err := os.ReadFile(c.Args[1])
		if err != nil {
			return run.Result{ExitCode: 1}, &run.ExitError{Name: c.Name, Code: 1}
		}
		var keep []string
		for _, l := range strings.Split(strings.TrimSuffix(string(b), "\n"), "\n") {
			if len(b) > 0 && !strings.HasPrefix(l, c.Args[3]+"=") {
				keep = append(keep, l)
			}
		}
		out := strings.Join(keep, "\n")
		if len(keep) > 0 {
			out += "\n"
		}
		return run.Result{}, os.WriteFile(c.Args[1], []byte(out), 0o644)
	}})
	h.Run.Add(run.Rule{Name: "/usr/sbin/service", Args: []string{"ntpd", run.AnyArg}, Fn: func(run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		h.restarts++
		return run.Result{}, nil
	}})
	h.Run.Add(run.Rule{Name: "/usr/bin/ntpq", Args: []string{"-pn"}, Fn: func(run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		return run.Result{Stdout: []byte(h.ntpq)}, nil
	}})
	// pfctl: the forms of the firewall module act on a pf that is running with the administrator's file
	h.Run.Add(run.Rule{Name: "/sbin/pfctl", Args: []string{run.RestArgs}, Fn: func(c run.Cmd) (run.Result, error) {
		h.mu.Lock()
		defer h.mu.Unlock()
		switch strings.Join(c.Args, " ") {
		case "-s info":
			st := "Disabled"
			if h.pfOn {
				st = "Enabled"
			}
			return run.Result{Stdout: []byte("Status: " + st + "\n")}, nil
		case "-s rules":
			out := ""
			for _, l := range strings.Split(h.pfLoaded, "\n") {
				if strings.HasPrefix(l, "anchor ") || strings.HasPrefix(l, "pass ") || strings.HasPrefix(l, "block ") {
					out += l + " all\n"
				}
			}
			return run.Result{Stdout: []byte(out)}, nil
		case "-n -f -":
			return run.Result{}, nil
		case "-f " + filepath.Join(h.Etc, "pf.conf"):
			b, err := os.ReadFile(filepath.Join(h.Etc, "pf.conf"))
			if err != nil {
				return run.Result{ExitCode: 1}, &run.ExitError{Name: c.Name, Code: 1, Stderr: "no pf.conf"}
			}
			h.pfLoaded = string(b)
			return run.Result{}, nil
		case "-e":
			h.pfOn = true
			return run.Result{}, nil
		case "-d":
			h.pfOn = false
			return run.Result{}, nil
		}
		return run.Result{ExitCode: 1}, &run.ExitError{Name: c.Name, Code: 1, Stderr: "unexpected"}
	}})
	var cmu sync.Mutex
	clock := time.Date(2026, 10, 30, 10, 15, 0, 0, time.UTC)
	cfg := priv.Config{StateDir: filepath.Join(dir, "privstate"), StorageFile: filepath.Join(dir, "priv.d", "storage.conf"),
		HostDir: filepath.Join(dir, "privhost"), HostManage: modules}
	l, err := priv.NewLocal(cfg, priv.Deps{Runner: h.Run, Etc: h.Etc,
		Now: func() time.Time { cmu.Lock(); defer cmu.Unlock(); clock = clock.Add(time.Second); return clock },
		// the deadline of a pending change: the test fires it with FireTimer
		AfterFunc: func(_ time.Duration, f func()) func() bool {
			h.mu.Lock()
			defer h.mu.Unlock()
			h.timer = f
			return func() bool { h.mu.Lock(); defer h.mu.Unlock(); armed := h.timer != nil; h.timer = nil; return armed }
		}}, priv.WithoutChown())
	if err != nil {
		t.Fatal(err)
	}
	h.Local = l
	return h
}

// Hostname is the running host name of the simulated host.
func (h *HostSim) Hostname() string { h.mu.Lock(); defer h.mu.Unlock(); return h.hostname }

// NTPRestarts counts the ntpd restarts and stops.
func (h *HostSim) NTPRestarts() int { h.mu.Lock(); defer h.mu.Unlock(); return h.restarts }

// SetNTPQ replaces what ntpq prints.
func (h *HostSim) SetNTPQ(s string) { h.mu.Lock(); defer h.mu.Unlock(); h.ntpq = s }

// File reads a file of the simulated etc directory.
func (h *HostSim) File(name string) string {
	b, _ := os.ReadFile(filepath.Join(h.Etc, name))
	return string(b)
}

// PFLoaded is the ruleset pf runs on the simulated host.
func (h *HostSim) PFLoaded() string { h.mu.Lock(); defer h.mu.Unlock(); return h.pfLoaded }

// FireTimer runs the timer of the pending change, as its deadline would; false when none is armed.
func (h *HostSim) FireTimer() bool {
	h.mu.Lock()
	f := h.timer
	h.timer = nil
	h.mu.Unlock()
	if f == nil {
		return false
	}
	f()
	return true
}
